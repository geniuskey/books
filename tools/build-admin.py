#!/usr/bin/env python3
"""Build /admin/ from the shared feedback markup. Run after feedback HTML edits."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
html = (root / 'feedback/index.html').read_text()
html = html.replace('독자 의견 · Books', '게시판 관리 · Books')
html = html.replace('https://books.euiyun.com/feedback/', 'https://books.euiyun.com/admin/')
html = html.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="robots" content="noindex">')
html = html.replace('<h1>독자 의견</h1>', '<h1>게시판 관리</h1>')
start = html.index('      <aside id="feedback-admin"')
end = html.index('</aside>', start) + len('</aside>')
panel = html[start:end]
html = html[:start] + html[end:]
html = html.replace('      <div class="feedback-workspace">', panel + '\n      <div class="feedback-workspace">')
(root / 'admin/index.html').write_text('<!-- Generated by tools/build-admin.py from feedback/index.html -->\n' + html)
